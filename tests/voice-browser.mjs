// Optional real-browser checks; JSC_PLAYWRIGHT may point to a temporary install.
import { writeFile } from 'node:fs/promises';
const engines = await import(process.env.JSC_PLAYWRIGHT || 'playwright');
const engine = process.env.JSC_ENGINE || 'chromium';
const browser = await engines[engine].launch({ executablePath: engine === 'chromium' ? process.env.JSC_CHROMIUM : undefined, headless: true, args: engine === 'chromium' ? ['--autoplay-policy=no-user-gesture-required'] : [] });
const page = await browser.newPage(); const errors = [];
page.on('pageerror', e => errors.push(String(e)));
const base = process.env.JSC_URL || 'http://127.0.0.1:5174';
await page.goto(base + '/tests/review.html');
await page.locator('h1').click();
const result = await page.evaluate(async () => {
  const { narration } = await import('/src/narration.js');
  const { setVoicePreference } = await import('/src/audio.js');
  const { COACHING } = await import('/src/data/coaching.js');
  const { runGame } = await import('/src/minigames/index.js');
  const { G, abortAll } = await import('/src/ui.js');
  const text = COACHING.greenhouse.goal;
  await narration.preload([text]);
  const start = performance.now();
  const spoken = new Promise(resolve => { const off = narration.subscribe(s => { if (s.status === 'speaking') { off(); resolve(performance.now() - start); } }); });
  const playing = narration.speak({ text, owner: 'check' });
  const cachedPlaybackMs = await spoken; narration.stop(); await playing;
  window.voiceCheck = { G, abortAll, narration, runGame };
  runGame('greenhouse', {}, { who: 'Lea', title: 'Voice coaching check', science: true });
  return { cachedPlaybackMs };
});
await page.getByRole('button', { name: 'Ask Rocky', exact: true }).click();
result.helpPauses = await page.evaluate(() => window.voiceCheck.G.helpOpen);
result.firstHint = await page.locator('.coach-help .voice-transcript:visible').first().innerText();
await page.getByRole('button', { name: 'Next hint', exact: true }).click();
result.secondHint = await page.locator('.coach-help .voice-transcript:visible').first().innerText();
await page.getByRole('button', { name: 'Mute narration', exact: true }).click();
await page.getByRole('button', { name: 'Enable narration', exact: true }).click();
result.narrationToggleKeepsText = result.secondHint === await page.locator('.coach-help .voice-transcript:visible').first().innerText();
await page.screenshot({ path: '/private/tmp/jsc-voice-help.png' });
await page.getByRole('button', { name: 'Back to mission', exact: true }).click();
result.helpResumes = await page.evaluate(() => !window.voiceCheck.G.helpOpen);
await page.evaluate(() => window.voiceCheck.abortAll());
result.abortStops = await page.evaluate(() => window.voiceCheck.narration.state.status === 'idle');
// Main game and touch layout use the same browser engine, not device certification.
await page.goto(base + '/?debug=voice');
await page.waitForFunction(() => !!window.__game);
result.mainLoads = await page.locator('#landing').isVisible();
await page.locator('.ld-start').click();
await page.getByRole('button', { name: 'Start Beginner →', exact: true }).click();
await page.locator('#rocky .voice-controls').waitFor();
result.rockyControls = await page.locator('#rocky .rocky-nav .voice-toggle').count() === 1 && await page.locator('#rocky .voice-transcript').count() === 0;
await page.locator('#rocky-next').click();
await page.locator('#rocky-next').click();
await page.locator('#rocky-close').click();
result.rockyCloseStops = await page.evaluate(async () => (await import('/src/narration.js')).narration.state.status === 'idle');
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(base + '/tests/review.html');
await page.locator('h1').click();
await page.evaluate(async () => { const { runGame } = await import('/src/minigames/index.js'); runGame('biosensor', {}, { science: true, who: 'Charles', title: 'Radiation biosensor' }); });
await page.getByRole('button', { name: 'Ask Rocky', exact: true }).click();
await page.getByRole('button', { name: 'Science', exact: true }).click();
result.mobileHelpFits = await page.locator('.coach-help .voice-controls').evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; });
await page.screenshot({ path: '/private/tmp/jsc-voice-mobile.png' });
await page.getByRole('button', { name: 'Back to mission', exact: true }).click();
await page.evaluate(async () => { (await import('/src/ui.js')).abortAll(); });
// Voice failures do not prevent loading or interacting with missions.
const failed = await browser.newPage();
await failed.route('**/assets/voice/**', route => route.abort());
await failed.goto(base + '/tests/review.html'); await failed.locator('h1').click();
await failed.bringToFront();
await failed.waitForFunction(async () => (await import('/src/audio.js')).speechAudio.ready());
result.missingAudioDetails = await failed.evaluate(async () => {
  const { narration } = await import('/src/narration.js');
  const ok = await narration.speak({ text: 'Missing audio should stay optional.' });
  return { ok, status: narration.state.status, hidden: document.hidden };
});
result.missingAudioSafe = !result.missingAudioDetails.ok && (result.missingAudioDetails.status === 'unavailable' || result.missingAudioDetails.status === 'idle' && result.missingAudioDetails.hidden);
await failed.close();
const blocked = await browser.newPage();
await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw Error('Storage blocked'); } }); });
await blocked.goto(base + '/tests/review.html'); await blocked.locator('h1').click();
result.blockedStorageSafe = await blocked.evaluate(async () => { const { setVoicePreference, settings } = await import('/src/audio.js'); setVoicePreference('narration', 'request'); return settings.narration === 'request'; });
await blocked.close();
await page.screenshot({ path: '/private/tmp/jsc-voice-check.png' });
result.errors = errors;
await writeFile(`/private/tmp/jsc-voice-results-${engine}.json`, JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
await browser.close();
if (errors.length || !result.helpPauses || !result.helpResumes || !result.narrationToggleKeepsText || !result.abortStops || !result.mainLoads || !result.mobileHelpFits || !result.missingAudioSafe || !result.blockedStorageSafe) process.exitCode = 1;
